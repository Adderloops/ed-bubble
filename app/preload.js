'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('edbubble', {
  onUpdate: (cb) => ipcRenderer.on('ed:update', (_e, snap) => cb(snap)),
  snapshot: () => ipcRenderer.invoke('ed:snapshot'),
  info: () => ipcRenderer.invoke('ed:info'),
  controls: () => ipcRenderer.invoke('ed:controls'),
  onControls: (cb) => ipcRenderer.on('ed:controls', (_e, c) => cb(c)),
  run: (id) => ipcRenderer.invoke('ed:run', id),
  suggest: (q) => ipcRenderer.invoke('ed:suggest', q),
  system: (name) => ipcRenderer.invoke('ed:system', name),
  markets: (q) => ipcRenderer.invoke('ed:markets', q),
  plot: (name, distance) => ipcRenderer.invoke('ed:plot', name, distance),
  plotCancel: () => ipcRenderer.invoke('ed:plot-cancel'),
  onPlotStatus: (cb) => ipcRenderer.on('ed:plot-status', (_e, st) => cb(st)),
  log: (msg) => ipcRenderer.send('ed:log', String(msg).slice(0, 4000)),
  bodies: () => ipcRenderer.invoke('ed:bodies'),
  recipes: () => ipcRenderer.invoke('ed:recipes'),
  colCosts: () => ipcRenderer.invoke('ed:colcosts'),
  shipData: () => ipcRenderer.invoke('ed:shipdata'),
  skull: () => ipcRenderer.invoke('ed:skull'),
  onSkull: (cb) => ipcRenderer.on('ed:skull', (_e, x) => cb(x)),
  skullConnect: () => ipcRenderer.invoke('ed:skull-connect'),
  skullDisconnect: () => ipcRenderer.invoke('ed:skull-disconnect'),
  rig: (op) => ipcRenderer.invoke('ed:rig', op),
  skullRefresh: () => ipcRenderer.invoke('ed:skull-refresh'),
  openSkullWeb: () => ipcRenderer.invoke('ed:open-skull-web'),
  here: () => ipcRenderer.invoke('ed:here'),
  onHere: (cb) => ipcRenderer.on('ed:here', (_e, h) => cb(h)),
  onBody: (cb) => ipcRenderer.on('ed:body', (_e, b) => cb(b)),
  onFuelStops: (cb) => ipcRenderer.on('ed:fuelstops', (_e, x) => cb(x)),
  ppTrack: (name) => ipcRenderer.invoke('ed:pp-track', name),
  clipboardRead: () => ipcRenderer.invoke('ed:clipboard-read'),
  targetSet: (text) => ipcRenderer.invoke('ed:target-set', text),
  targetClear: () => ipcRenderer.invoke('ed:target-clear'),
  copy: (text) => ipcRenderer.invoke('ed:copy', text),
  settings: () => ipcRenderer.invoke('ed:settings'),
  setSetting: (key, value) => ipcRenderer.invoke('ed:settings-set', key, value),
  displays: () => ipcRenderer.invoke('ed:displays'),
  moveToDisplay: (id) => ipcRenderer.invoke('ed:display-move', id),
  bindsImport: () => ipcRenderer.invoke('ed:binds-import'),
  bindsAuto: () => ipcRenderer.invoke('ed:binds-auto'),
  bindsReload: () => ipcRenderer.invoke('ed:binds-reload'),
  bindsFolder: () => ipcRenderer.invoke('ed:binds-folder'),
  openData: () => ipcRenderer.invoke('ed:open-data'),
  open: (site, name, address) => ipcRenderer.invoke('ed:open', { site, name, address }),
  builds: () => ipcRenderer.invoke('ed:builds'),
  buildImport: () => ipcRenderer.invoke('ed:build-import'),
  buildDelete: (id) => ipcRenderer.invoke('ed:build-delete', id),
  shipExport: (kind) => ipcRenderer.invoke('ed:ship-export', kind),
  buySearch: (item) => ipcRenderer.invoke('ed:buy-search', item),
  neutronPlot: (opts) => ipcRenderer.invoke('ed:neutron-plot', opts),
  neutronClear: () => ipcRenderer.invoke('ed:neutron-clear'),
  tradeSell: (q) => ipcRenderer.invoke('ed:trade-sell', q),
  tradeRoute: (q) => ipcRenderer.invoke('ed:trade-route', q),
  tradeRouteClear: () => ipcRenderer.invoke('ed:trade-route-clear'),
});
